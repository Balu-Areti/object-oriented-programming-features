package com.java.oop.abstraction;

public class Customer {
    int id;
    String name;
    String email;
    String phone;
    String address;

    public Customer(int id, String name, String email, String phone,  String address) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.phone = phone;
        this.address = address;
    }
}
